GLYPHES = G
HAUTEUR = 7


def largeur(texte, z=1):
    """Largeur en pixels d'un texte à l'agrandissement z (1 colonne d'espace entre les lettres)."""
    return z * (sum(len(G[c][0]) + 1 for c in texte) - 1) if texte else 0


def main():
    texte = "".join(G)
    L, H = largeur(texte) + 2, HAUTEUR + 2
    px = [(0, 0, 0, 0)] * (L * H)
    x = 1
    for c in texte:
        for y, ligne in enumerate(G[c]):
            for i, ch in enumerate(ligne):
                if ch == "#":
                    px[(y + 1) * L + x + i] = (0x1D, 0x1B, 0x2E, 255)
        x += len(G[c][0]) + 1
    brut = b"".join(b"\x00" + bytes(v for p in px[y * L:(y + 1) * L] for v in p) for y in range(H))
    def m(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    sortie = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ico5x7-planche.png")
    with open(sortie, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + m(b"IHDR", struct.pack(">IIBBBBB", L, H, 8, 6, 0, 0, 0))
                + m(b"IDAT", zlib.compress(brut, 9)) + m(b"IEND", b""))
    print(f"{len(G)} glyphes, planche {L}×{H} : {sortie}")


if __name__ == "__main__":
    main()
